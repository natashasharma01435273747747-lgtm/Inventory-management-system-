  const productById = new Map(products.map((p) => [p.id, p]));

  function buildSeedSale(
    idx: number,
    offsetDays: number,
    hour: number,
    minute: number,
    customerName: string,
    customerPhone: string,
    paymentMethod: 'Cash' | 'UPI' | 'Card',
    cashierName: string,
    lines: Array<{ productId: string; quantity: number }>,
    discount = 0
  ): SaleRecord {
    const items = lines
      .map(({ productId, quantity }) => {
        const p = productById.get(productId);
        if (!p) return null;
        return {
          productId: p.id,
          productName: p.name,
          sku: p.sku,
          category: p.category,
          unit: p.unit,
          quantity,
          unitPrice: p.price,
          costPrice: p.costPrice,
          lineTotal: p.price * quantity,
        };
      })
      .filter((x): x is NonNullable<typeof x> => x !== null);

    const subtotal = items.reduce((s, i) => s + i.lineTotal, 0);
    const totalCost = items.reduce((s, i) => s + i.costPrice * i.quantity, 0);
    const gstAmount = Math.round(subtotal * 0.05);
    const totalAmount = Math.max(0, subtotal + gstAmount - discount);
    const grossProfit = Math.max(0, subtotal - discount - totalCost);

    return {
      id: `sale-seed-${idx}`,
      invoiceNumber: `INV-2026-${String(1040 + idx).padStart(4, '0')}`,
      date: getLocalIsoDate(offsetDays),
      createdAt: isoTimestampAt(offsetDays, hour, minute),
      customerName,
      customerPhone,
      paymentMethod,
      cashierName,
      items,
      subtotal,
      gstAmount,
      discount,
      totalAmount,
      totalCost,
      grossProfit,
    };
  }

